// 今の言語の文言。ID.setLanguage('ja') か ID.setLanguage('en') で入れ替える。
ID.texts = {};
ID.setLanguage = function (lang) {
  var src = ID.textsAll[lang] || ID.textsAll.ja, k;
  for (k in ID.texts) delete ID.texts[k];
  for (k in src) ID.texts[k] = src[k];
};
ID.setLanguage('ja');
